import { expect, test } from '@playwright/test';

test('prompt answer mode merges variants, persists and applies across editors and preview', async ({ page }, info) => {
  await page.goto('/#/p/1/settings');
  await expect(page.getByRole('tablist', { name: 'Разделы настроек' }).getByRole('tab')).toHaveText(['Внешний вид', 'Интенты и NLU', 'Промпты', 'Спецификации']);
  await page.getByRole('tab', { name: 'Промпты', exact: true }).click();
  const defaultToggle = page.getByRole('switch', { name: 'Разделять краткие и полные ответы', exact: true });
  await expect(defaultToggle).toBeEnabled();
  await expect(defaultToggle).not.toBeChecked();
  await defaultToggle.click();
  await expect(defaultToggle).toBeChecked();
  await page.goto('/#/p/1/lists/prompts');
  const full = page.getByRole('textbox', { name: /^Полный ответ, вариант/ });
  const short = page.getByRole('textbox', { name: /^Короткий ответ, вариант/ });
  await expect(full.first()).toBeVisible();
  const before = [...await full.evaluateAll(nodes => nodes.map(n => (n as HTMLTextAreaElement).value)), ...await short.evaluateAll(nodes => nodes.map(n => (n as HTMLTextAreaElement).value))];
  await page.goto('/#/p/1/settings');
  await page.getByRole('tab', { name: 'Промпты', exact: true }).click();
  const toggle = page.getByRole('switch', { name: 'Разделять краткие и полные ответы', exact: true });
  await expect(toggle).toBeEnabled();
  await expect(toggle).toBeChecked();
  await toggle.click();
  await expect(toggle).not.toBeChecked();
  await page.screenshot({ path: info.outputPath('prompt-settings-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: info.outputPath('prompt-settings-mobile.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.reload();
  await page.getByRole('tab', { name: 'Промпты', exact: true }).click();
  await expect(toggle).not.toBeChecked();
  await page.goto('/#/p/1/lists/prompts');
  const unified = page.getByRole('textbox', { name: /^Ответ ассистента, вариант/ });
  await expect(unified.first()).toBeVisible();
  expect(await unified.evaluateAll(nodes => nodes.map(n => (n as HTMLTextAreaElement).value))).toEqual(before);
  await expect(short).toHaveCount(0);
  await page.goto('/#/p/1/templates/responses');
  await expect(page.getByRole('button', { name: 'Добавить вариант', exact: true })).toHaveCount(1);
  await page.goto('/#/p/1/scenarios');
  await page.getByRole('tab', { name: /^Промпты/ }).click();
  await expect(page.getByText('Ответ ассистента', { exact: true })).toBeVisible();
  await expect(page.getByText('Короткий ответ', { exact: true })).toHaveCount(0);
  await page.screenshot({ path: info.outputPath('unified-prompts-desktop.png') });
  await page.getByRole('tab', { name: /^Предпросмотр/ }).click();
  await expect(page.locator('article')).toContainText('Ответ ассистента');
  await expect(page.locator('article')).not.toContainText('Короткий ответ');
  await page.goto('/#/p/1/settings');
  await page.getByRole('tab', { name: 'Промпты', exact: true }).click();
  await toggle.click();
  await expect(toggle).toBeChecked();
  await page.goto('/#/p/1/lists/prompts');
  await expect(full.first()).toBeVisible();
  expect(await full.evaluateAll(nodes => nodes.map(n => (n as HTMLTextAreaElement).value))).toEqual(before);
  await expect(short).toHaveCount(0);
});
